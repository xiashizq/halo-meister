    /// <summary>
    /// True only when all three overlay files are present in Paks.
    /// Dedicated features (Allegiance Demo scaffolds) should gate on the
    /// default campaign extras instance.
    /// </summary>
    public bool IsInstalled()
    {
        try
        {
            string paks = ResolvePaksDirectory();
            return HasCompleteTriplet(paks, _mod.Stem) ||
                   _mod.LegacyStems.Any(stem => HasCompleteTriplet(paks, stem));
        }
        catch (DirectoryNotFoundException)
        {
            return false;
        }
    }

    public bool IsBundledAvailable()
    {
        try
        {
            _ = ResolveBundledSources();
            return true;
        }
        catch (FileNotFoundException)
        {
            return false;
        }
    }

    /// <summary>
    /// True when the app-bundled triplet matches the trusted fingerprint for
    /// this build. Tampered or corrupt bundles must not drive update prompts.
    /// An empty expected fingerprint means the pack is not fingerprint-locked
    /// yet (used while the character AI overlay is being split out).
    /// </summary>
    public bool IsBundledIntact()
    {
        try
        {
            string[] sources = ResolveBundledSources();
            string? fingerprint = TryFingerprintFiles(sources);
            return IsTrustedFingerprint(fingerprint);
        }
        catch (FileNotFoundException)
        {
            return false;
        }
    }

    public static IReadOnlyList<BuiltinModCatalogStatus> GetCatalogStatuses()
    {
        return BuiltinModCatalog.All
            .Select(definition =>
